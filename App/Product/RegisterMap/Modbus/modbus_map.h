/*
 * Canonical Pyxis Modbus map (Milestone C).
 *
 * Addresses in this file are zero-based offsets, as required by the Modbus
 * engine.  The corresponding wire/documentation addresses are 40001 + offset
 * for holding registers and 30001 + offset for input registers.
 *
 * This migration keeps the existing Pyxis encodings and dense storage model.
 * The lists are deliberately free of callbacks and application behavior;
 * those remain in the product adapters until the later milestones.
 */

