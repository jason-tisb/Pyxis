/*
 * The lookup address is a zero-based offset in the selected register space.
 * ModbusMap_Find() returns the entry whose half-open range contains address:
 * [entry->start_address, entry->start_address + entry->count).
 * ModbusMap_FindById() returns NULL for an invalid ID.
 */
const modbus_map_entry_t *ModbusMap_Find(
    modbus_map_register_type_t type, uint16_t address);

/*
 * Resolve one word and return its zero-based offset within the containing row.
 * Both output pointers are required; supplied outputs are cleared on failure.
 */
bool ModbusMap_Resolve(
    modbus_map_register_type_t type, uint16_t address,
    const modbus_map_entry_t **entry, uint16_t *word_offset);

/* Checks only 16-bit Modbus address-space bounds, not map coverage/access. */
bool ModbusMap_IsAddressRangeValid(
    uint16_t start_address, uint16_t count);

const modbus_map_entry_t *ModbusMap_FindById(
    pyxis_modbus_reg_id_t id);

const modbus_map_entry_t *ModbusMap_Entries(void);
uint16_t ModbusMap_Count(void);

/* Value legality is independent of whether the entry is writable. */
bool ModbusMap_ValidateValue(
    const modbus_map_entry_t *entry, uint16_t value);

static inline bool ModbusMap_IsBootApplied(
    const modbus_map_entry_t *entry)
{
    return (entry != NULL) &&
           (entry->apply_policy == MODBUS_APPLY_ON_BOOT);
}

bool ModbusMap_ValidateIntegrity(void);

